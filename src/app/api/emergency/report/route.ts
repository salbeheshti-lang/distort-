// DISTORT — /api/emergency/report
// POST: persist a recovery attempt + optional probe result
//
// Input: ReportRequest = { planId, attempt: Omit<RecoveryAttempt, "planId">, probeResult?: ProbeResult }
// Output: { ok: true }
//
// All string fields are scrubbed via scrubSensitive() before persistence —
// this is the LAST line of defense against leaking credentials/UUIDs/URLs
// into the DB. The client is also expected to scrub, but we don't trust it.
//
// Rate limit: 60 reports/minute per IP.

import { NextRequest, NextResponse } from "next/server";
import { db } from "@/lib/db";
import { isRateLimited, getClientIp } from "@/lib/emergency-connectivity/rate-limiter";
import { scrubSensitive } from "@/lib/emergency-connectivity/types";
import type { ReportRequest } from "@/lib/emergency-connectivity/types";

const RATE_LIMIT_MAX = 60;
const RATE_LIMIT_WINDOW_MS = 60_000; // 1 minute

function scrubString(s: string | null | undefined): string | null {
  if (s == null) return null;
  return scrubSensitive(String(s));
}

export async function POST(req: NextRequest) {
  // Rate limit
  const ip = getClientIp(req);
  if (isRateLimited(`report:${ip}`, RATE_LIMIT_MAX, RATE_LIMIT_WINDOW_MS)) {
    return NextResponse.json(
      { error: "Too many report requests. Try again in a minute." },
      { status: 429 }
    );
  }

  // Parse body
  let body: ReportRequest;
  try {
    body = (await req.json()) as ReportRequest;
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  if (!body || typeof body !== "object") {
    return NextResponse.json({ error: "Body must be a JSON object" }, { status: 400 });
  }
  if (!body.planId || typeof body.planId !== "string") {
    return NextResponse.json({ error: "planId is required" }, { status: 400 });
  }
  if (!body.attempt || typeof body.attempt !== "object") {
    return NextResponse.json({ error: "attempt is required" }, { status: 400 });
  }

  const a = body.attempt;
  if (!a.candidateId || typeof a.candidateId !== "string") {
    return NextResponse.json({ error: "attempt.candidateId is required" }, { status: 400 });
  }
  if (typeof a.attemptNumber !== "number" || a.attemptNumber < 1) {
    return NextResponse.json({ error: "attempt.attemptNumber must be >= 1" }, { status: 400 });
  }
  if (!a.state || typeof a.state !== "string") {
    return NextResponse.json({ error: "attempt.state is required" }, { status: 400 });
  }
  if (!a.result || typeof a.result !== "string") {
    return NextResponse.json({ error: "attempt.result is required" }, { status: 400 });
  }

  const candidateLabel = a.candidateLabel || a.candidateId;
  const reason = a.reason || "";
  const startedAt = a.startedAt ? new Date(a.startedAt) : new Date();
  const endedAt = a.endedAt ? new Date(a.endedAt) : null;
  const latencyMs = typeof a.latencyMs === "number" ? a.latencyMs : null;

  // Scrub EVERY string field before persistence — never trust the client.
  // planId is generated by us (server-side) so it's safe, but we scrub anyway
  // for defense-in-depth.
  try {
    await db.recoveryAttempt.create({
      data: {
        planId: scrubString(body.planId) || body.planId,
        candidateId: scrubString(a.candidateId) || a.candidateId,
        candidateLabel: scrubString(candidateLabel) || candidateLabel,
        attemptNumber: a.attemptNumber,
        state: scrubString(a.state) || a.state,
        result: scrubString(a.result) || a.result,
        reason: scrubString(reason) || "",
        latencyMs,
        startedAt,
        endedAt,
      },
    });
  } catch (err) {
    return NextResponse.json(
      { error: "Failed to persist recovery attempt", detail: String(err) },
      { status: 500 }
    );
  }

  // Optionally persist the probe result
  if (body.probeResult && typeof body.probeResult === "object") {
    const p = body.probeResult;
    if (p.structural && typeof p.structural === "string") {
      try {
        await db.probeResult.create({
          data: {
            configId: scrubString(p.configId) || null,
            planId: scrubString(body.planId) || body.planId,
            structural: scrubString(p.structural) || p.structural,
            reachability: scrubString(p.reachability) || p.reachability || "not-probed",
            tunnel: scrubString(p.tunnel) || p.tunnel || "not-attempted",
            latencyMs: typeof p.latencyMs === "number" ? p.latencyMs : null,
            exitIp: scrubString(p.exitIp) || null,
            exitCountry: scrubString(p.exitCountry) || null,
            failureReason: scrubString(p.failureReason) || null,
            probedAt: p.probedAt ? new Date(p.probedAt) : new Date(),
          },
        });
      } catch (err) {
        // Don't fail the whole report if probe persistence fails —
        // the attempt was already recorded.
        return NextResponse.json(
          {
            ok: true,
            warning: "Recovery attempt persisted but probe-result persistence failed",
            detail: String(err),
          },
          { status: 200 }
        );
      }
    }
  }

  return NextResponse.json({ ok: true });
}
