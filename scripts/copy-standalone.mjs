// Cross-platform copy script for Next.js standalone build
// Copies .next/static, public/, and Prisma query engine into .next/standalone/
// Works on Windows, macOS, and Linux (uses Node.js fs)

import { cpSync, mkdirSync, existsSync, readdirSync, copyFileSync, statSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const standaloneDir = join(root, ".next", "standalone");
const staticSrc = join(root, ".next", "static");
const staticDest = join(standaloneDir, ".next", "static");
const publicSrc = join(root, "public");
const publicDest = join(standaloneDir, "public");

if (!existsSync(standaloneDir)) {
  console.error("✗ Standalone dir not found. Did `next build` run?");
  process.exit(1);
}

console.log("→ Copying .next/static → .next/standalone/.next/static");
mkdirSync(dirname(staticDest), { recursive: true });
cpSync(staticSrc, staticDest, { recursive: true });
console.log("  ✓ Done");

console.log("→ Copying public/ → .next/standalone/public");
cpSync(publicSrc, publicDest, { recursive: true });
console.log("  ✓ Done");

// CRITICAL: Copy Prisma query engine binary.
// Without this, the Next.js server crashes on every DB query:
// "Prisma Client could not locate the Query Engine."
// The engine is a native binary (.node on Windows, .so.node on Linux, .dylib.node on macOS)
// that's generated by `prisma generate` into node_modules/.prisma/client/.
// Next.js standalone tracing doesn't include native binaries, so we copy them manually.
console.log("→ Copying Prisma query engine → .next/standalone/node_modules/.prisma/client");
const prismaEngineSrc = join(root, "node_modules", ".prisma", "client");
const prismaEngineDest = join(standaloneDir, "node_modules", ".prisma", "client");

if (existsSync(prismaEngineSrc)) {
  mkdirSync(prismaEngineDest, { recursive: true });

  // Copy all engine files (libquery_engine-*.so.node, query_engine-*.dll.node, etc.)
  const engineFiles = readdirSync(prismaEngineSrc).filter((f) =>
    f.match(/(libquery_engine|query_engine).*\.(so\.node|dll\.node|dylib\.node|node)$/) ||
    f === "schema.prisma" ||
    f === "index.js" ||
    f === "index.d.ts"
  );

  for (const file of engineFiles) {
    const srcFile = join(prismaEngineSrc, file);
    const destFile = join(prismaEngineDest, file);
    try {
      const stat = statSync(srcFile);
      if (stat.size > 0) {
        copyFileSync(srcFile, destFile);
        console.log(`  ✓ ${file} (${(stat.size / 1024 / 1024).toFixed(1)} MB)`);
      }
    } catch (e) {
      console.warn(`  ⚠ Failed to copy ${file}: ${e.message}`);
    }
  }
} else {
  console.warn("  ⚠ Prisma engine not found at node_modules/.prisma/client/");
  console.warn("    Run `bunx prisma generate` before building.");
}

// Also copy @prisma/client if not already there
const prismaClientSrc = join(root, "node_modules", "@prisma", "client");
const prismaClientDest = join(standaloneDir, "node_modules", "@prisma", "client");
if (existsSync(prismaClientSrc) && !existsSync(prismaClientDest)) {
  console.log("→ Copying @prisma/client");
  mkdirSync(dirname(prismaClientDest), { recursive: true });
  cpSync(prismaClientSrc, prismaClientDest, { recursive: true });
  console.log("  ✓ Done");
}

// Copy schema.sql + seed.sql so the Next.js server can auto-migrate
console.log("→ Copying schema.sql + seed.sql → .next/standalone/resources/db");
const dbSrcDir = join(root, "desktop", "resources", "db");
const dbDestDir = join(standaloneDir, "resources", "db");
if (existsSync(dbSrcDir)) {
  mkdirSync(dbDestDir, { recursive: true });
  cpSync(dbSrcDir, dbDestDir, { recursive: true });
  console.log("  ✓ Done");
} else {
  console.warn("  ⚠ desktop/resources/db not found — schema/seed SQL not bundled");
}

console.log("✓ Standalone bundle complete");
